// ── 판정 ────────────────────────────────────────────────────────────
// 임계값은 scripts/calibrate.ts 의 몬테카를로 결과로 정했다.
// 문항이 바뀌면 `npm run calibrate` 를 다시 돌려서 갱신할 것.

export const BELIEF_THRESHOLD = 21;
export const ACTIVE_THRESHOLD = 22;
/** 한 번 넘긴 사람을 밀정형으로 볼 신념 상한 */
export const INFORM_BELIEF_CEILING = 16;
/** 협력자 중 "한때 신념이 있었던" 쪽(전향)과 아예 없던 쪽(기회주의)의 경계 */
export const CONVERT_FLOOR = 19;

export type Score = {
  belief: number;
  active: number;
  direct: number;
  /** 사람을 넘긴 횟수 (0–2) */
  informs: number;
};

export function decide({ belief, active, direct, informs }: Score): string {
  const hasBelief = belief >= BELIEF_THRESHOLD;
  const isActive = active >= ACTIVE_THRESHOLD;
  const isDirect = direct >= 0;

  // 밀정형 판정.
  //   두 번 넘겼으면 신념 점수와 무관하게 밀정형 — 한 번은 압박이지만
  //   두 번은 습관이다.
  //   한 번만 넘겼다면 초안대로 신념이 낮을 때만 밀정형으로 본다. 끝까지
  //   버티다 한 번 무너진 사람까지 밀정으로 부르지는 않는다.
  if (informs >= 2 || (informs === 1 && belief < INFORM_BELIEF_CEILING))
    return "informant";

  // 신념이 남아 있는 쪽 — 얼마나 적극적이었나, 그리고 정면이었나 우회였나
  if (hasBelief) {
    if (isActive) return isDirect ? "armed" : "org";
    return isDirect ? "hermit" : "inner";
  }

  // 협력한 쪽.
  //   소극적이었다면 그냥 시키는 만큼만 한 사람이다. 정면이든 우회든
  //   생계형 순응자로 본다. 실제로 가장 많은 사람이 여기 있었다.
  //   (초안은 이 자리에 이중생활형을 앉혀 뒀는데, 이중생활형은 "반장을 맡고
  //    보고를 올린" 적극적인 사람이라 설명과 사분면이 어긋나 있었다.)
  if (!isActive) return "survivor";

  // 적극적으로 체제 안에 들어갔고, 그러면서 뒤로 눙쳤다면 이중생활형
  if (!isDirect) return "double";

  // 앞장서서 협력했다면, 한때 신념이 있었는지로 갈린다.
  // 전향 지식인은 스스로를 설득한 사람이고, 기회주의자는 애초에 설득할
  // 신념이 없었던 사람이다.
  return belief >= CONVERT_FLOOR ? "convert" : "opportunist";
}
