function esc(s) {
  return String(s).replace(/'/g, "''");
}

// 프롬프트 기반 결정적 PRNG → 정답 위치를 보기 4곳에 골고루 분산(재생성해도 동일).
function hashSeed(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
function mulberry32(a) {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
// 보기 순서를 섞고 정답의 새 인덱스를 돌려준다.
function shuffleChoices(prompt, choices, ans) {
  const rnd = mulberry32(hashSeed(prompt));
  const idx = choices.map((_, i) => i);
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  return [idx.map((i) => choices[i]), idx.indexOf(ans)];
}

function buildCategorySql(category) {
  const src = SRC[category];
  const rows = [];
  for (let d = 1; d <= 5; d++) {
    for (const [prompt, choices, ans, expl] of DATA[category][d]) {
      const [shChoices, shAns] = shuffleChoices(prompt, choices, ans);
      const choicesJson = JSON.stringify(shChoices);
      rows.push(
        `  ('${esc(prompt)}', '${esc(choicesJson)}'::jsonb, ${shAns}, '${esc(expl)}', ${d}, '${esc(src[0])}', '${src[1]}')`,
      );
    }
  }
  return `-- 5초 브리핑 시드: ${category} (난이도 1~5 각 16문제 = 80문제)
-- 여러 번 실행해도 content_hash(prompt) 기준으로 중복되지 않아요.
with seed(prompt, choices, answer_index, explanation, difficulty, source_name, source_url) as (
  values
${rows.join(',\n')}
)
insert into public.questions (
  category, prompt, choices, answer_index, explanation, difficulty,
  source_name, source_url, fact_checked_at, expires_at, status,
  ai_generated, content_hash, reviewed_by
)
select
  '${category}', prompt, choices, answer_index, explanation, difficulty,
  source_name, source_url, now(), now() + interval '365 days', 'approved',
  false, encode(digest(prompt, 'sha256'), 'hex'), 'mvp-seed'
from seed
on conflict (content_hash) do update set
  category = excluded.category,
  choices = excluded.choices,
  answer_index = excluded.answer_index,
  explanation = excluded.explanation,
  difficulty = excluded.difficulty,
  status = 'approved',
  expires_at = excluded.expires_at,
  fact_checked_at = excluded.fact_checked_at;

select difficulty, count(*) from public.questions
where category='${category}' and status='approved' group by difficulty order by difficulty;
`;
}

