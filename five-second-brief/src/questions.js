// 순서를 섞어 20문제를 낸다(보유량이 적으면 있는 만큼).
export function getDailySet(category) {
  const seed = (bank[category] ?? []).slice();
  for (let i = seed.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [seed[i], seed[j]] = [seed[j], seed[i]];
  }
  const n = Math.min(20, seed.length);
  return Array.from({ length: n }, (_, i) => {
    const q = seed[i];
    return { id:`local-${category}-${i+1}`, prompt:q[0], choices:q[1], answer:q[2], explanation:q[3] };
  });
}
